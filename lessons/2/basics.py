# Арифметичні оператори
a = 10
b = 3
print("--- Арифметичні оператори ---")
print(f"Додавання (a + b): {a + b}")          # 13
print(f"Віднімання (a - b): {a - b}")         # 7
print(f"Множення (a * b): {a * b}")           # 30
print(f"Ділення (a / b): {a / b}")            # 3.3333333333333335 (завжди float)

# Цілочисельні оператори
print(f"Ділення без остачі (a // b): {a // b}") # 3
print(f"Остача від ділення (a % b): {a % b}")   # 1
print(f"Піднесення до степеня (a ** b): {a ** b}") # 1000 (10 в кубі)

# Оператори порівняння (повертають True або False)
print("\n--- Оператори порівняння ---")        # cимвол \n означає вивід з нового рядка
print(f"Рівність (a == b): {a == b}")          # False
print(f"Нерівність (a != b): {a != b}")        # True
print(f"Більше (a > b): {a > b}")              # True
print(f"Менше або рівно (a <= b): {a <= b}")   # False

# Логічні оператори (and, or, not)
print("\n--- Логічні оператори ---")
x = True
y = False
print(f"Логічне 'І' (x and y): {x and y}")      # False (обидва мають бути True)
print(f"Логічне 'АБО' (x or y): {x or y}")      # True (хоча б один має бути True)
print(f"Логічне 'НЕ' (not x): {not x}")         # False (інверсія)

# Оператори присвоєння та скорочення
print("\n--- Оператори присвоєння ---")
c = 5
c += 2  # еквівалентно: c = c + 2
print(f"Скорочене додавання (c += 2): {c}")   # 7


