# ------------------------------------------------------------------------------
# 1. СПИСКИ (Lists) — динамічні, впорядковані, змінювані колекції []
# ------------------------------------------------------------------------------
print("--- 1. СПИСКИ (LISTS) ---")

# Створення списку
fruits = ["яблуко", "банан", "апельсин"]
mixed = [1, "текст", 3.14, True]  # можуть містити різні типи даних

# Індексація та зрізи (слайси) — працюють так само, як у рядках
print(f"Перший елемент fruits[0]: {fruits[0]}")       # яблуко
print(f"Останній елемент fruits[-1]: {fruits[-1]}")     # апельсин
print(f"Зріз fruits[0:2]: {fruits[0:2]}")             # ['яблуко', 'банан']

# Змінюваність (мутабельність) списків
fruits[1] = "груша"
print(f"Список після зміни елемента: {fruits}")       # ['яблуко', 'груша', 'апельсин']

# Основні методи списків
fruits.append("ківі")          # додає елемент в кінець
print(f"Після .append(): {fruits}")

fruits.insert(1, "манго")      # додає "манго" на індекс 1
print(f"Після .insert(): {fruits}")

fruits.remove("груша")         # видаляє елемент за значенням
print(f"Після .remove(): {fruits}")

popped = fruits.pop(2)         # видаляє та повертает елемент за індексом (2 — апельсин)
print(f"Після .pop(2): {fruits} (видалено елемент: {popped})")

# Функції над списками
numbers = [5, 2, 9, 1, 7]
print(f"Кількість елементів len(): {len(numbers)}")  # 5
print(f"Сума елементів sum(): {sum(numbers)}")        # 24
print(f"Максимум max(): {max(numbers)}")              # 9
print(f"Мінімум min(): {min(numbers)}")              # 1

# Сортування
numbers.sort()                 # сортує список на місці
print(f"Після .sort() (по зростанню): {numbers}")
numbers.reverse()              # розгортає список
print(f"Після .reverse() (по спаданню): {numbers}")


# ------------------------------------------------------------------------------
# 2. КОРТЕЖІ (Tuples) — впорядковані, НЕЗМІНЮВАНІ колекції ()
# ------------------------------------------------------------------------------
print("\n--- 2. КОРТЕЖІ (TUPLES) ---")

# Створення кортежу (значення не можна змінити, додати або видалити після створення)
coordinates = (50.45, 30.52)   # координати Києва
person = ("Олексій", 25, "Київ")

print(f"Елемент кортежу person[0]: {person[0]}") # Олексій
print(f"Довжина кортежу len(coordinates): {len(coordinates)}") # 2

# Спроба змінити елемент викликала б помилку TypeError:
# coordinates[0] = 40.0 -> ПОМИЛКА! Кортежі незмінні.

# Головна перевага кортежів: вони швидші за списки і захищені від випадкових змін.
# Розпакування кортежу (Tuple Unpacking)
lat, lon = coordinates
print(f"Розпаковані змінні: Широта = {lat}, Довгота = {lon}")


# ------------------------------------------------------------------------------
# 3. СЛОВНИКИ (Dictionaries) — невпорядковані колекції пар "ключ: значення" {}
# ------------------------------------------------------------------------------
print("\n--- 3. СЛОВНИКИ (DICTIONARIES) ---")

# Створення словника (ключі мають бути унікальними)
user = {
    "name": "Іван",
    "age": 30,
    "city": "Львів",
    "skills": ["Python", "SQL"]
}

# Доступ до значень за ключем
print(f"Ім'я користувача user['name']: {user['name']}") # Іван

# Безпечний доступ через .get() (якщо ключа немає, поверне None замість помилки)
print(f"Доступ через .get('email'): {user.get('email')}") # None
print(f"Доступ через .get з дефолтним значенням: {user.get('email', 'не вказано')}")

# Додавання та зміна значень
user["age"] = 31               # зміна існуючого значення
user["email"] = "ivan@mail.com" # додавання нової пари "ключ: значення"
print(f"Оновлений словник: {user}")

# Видалення елементів
del user["city"]               # видалення за ключем
removed_value = user.pop("age") # видалення із поверненням значення
print(f"Після видалення city та age: {user} (вік був: {removed_value})")

# Отримання списків ключів, значень та пар
print(f"Тільки ключі (.keys()): {list(user.keys())}")
print(f"Тільки значення (.values()): {list(user.values())}")
print(f"Пари ключ-значення (.items()): {list(user.items())}")


# ------------------------------------------------------------------------------
# 4. ПРАКТИЧНИЙ ПРИКЛАД
# ------------------------------------------------------------------------------
print("\n--- 4. ПРАКТИЧНИЙ ПРИКЛАД ---")

# Список словників (імітація бази даних студентів)
students = [
    {"name": "Марія", "grades": [95, 88, 100]},
    {"name": "Петро", "grades": [70, 82, 65]},
    {"name": "Олена", "grades": [90, 92, 85]}
]

# Обчислюємо середній бал для першого студента у списку
first_student = students[0]
avg_grade = sum(first_student["grades"]) / len(first_student["grades"])

print(f"Студент: {first_student['name']}")
print(f"Усі оцінки: {first_student['grades']}")
print(f"Середній бал (округлений): {round(avg_grade, 1)}")